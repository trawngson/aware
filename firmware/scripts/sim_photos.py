"""Build the photos in sim/photos into the simulator firmware (env:sim).

Wokwi has no camera, so each scan in the simulator sends the next of these
photos. They are shrunk to at most 640 px with macOS `sips` (JPEG, PNG and
HEIC all work) and written to sim/generated/sim_photos.h, which git ignores.
"""

import json
import os
import shutil
import struct
import subprocess

Import("env")  # noqa: F821  (provided by PlatformIO)

PROJECT = env.subst("$PROJECT_DIR")  # noqa: F821
SOURCE = os.path.join(PROJECT, "sim", "photos")
GENERATED = os.path.join(PROJECT, "sim", "generated")
SHRUNK = os.path.join(GENERATED, "photos")
EXTENSIONS = {".jpg", ".jpeg", ".png", ".heic"}
MAX_SIDE = 640
# About the size the OV2640 makes at its default quality (20-50 KB at
# 640 x 480), so uploads in the simulator take as long as on the board.
JPEG_QUALITY = 60
STAMP = f"{MAX_SIDE} {JPEG_QUALITY}"


def jpeg_size(data):
    """Width and height from the JPEG frame header, or (0, 0)."""
    i = 2
    while i + 9 < len(data):
        if data[i] != 0xFF:
            i += 1
            continue
        marker = data[i + 1]
        if marker in (0xC0, 0xC1, 0xC2):
            height, width = struct.unpack(">HH", data[i + 5 : i + 9])
            return width, height
        if marker in (0x01, 0xD8) or 0xD0 <= marker <= 0xD7:
            i += 2
            continue
        i += 2 + struct.unpack(">H", data[i + 2 : i + 4])[0]
    return 0, 0


def shrink(source, target):
    if os.path.exists(target) and os.path.getmtime(target) >= os.path.getmtime(source):
        return
    if shutil.which("sips"):
        subprocess.run(
            ["sips", "-Z", str(MAX_SIDE), "-s", "format", "jpeg", "-s", "formatOptions", str(JPEG_QUALITY),
             source, "--out", target],
            check=True,
            stdout=subprocess.DEVNULL,
        )
    elif source.lower().endswith((".jpg", ".jpeg")):
        shutil.copyfile(source, target)
    else:
        raise SystemExit(f"sim_photos: {source} needs macOS sips to convert; use a JPEG instead")


def build():
    # Shrink every photo again when the size or quality settings change.
    stamp_path = os.path.join(GENERATED, "settings.txt")
    if os.path.isdir(SHRUNK):
        old_stamp = open(stamp_path).read() if os.path.exists(stamp_path) else ""
        if old_stamp != STAMP:
            shutil.rmtree(SHRUNK)
    os.makedirs(SHRUNK, exist_ok=True)
    with open(stamp_path, "w") as handle:
        handle.write(STAMP)
    names = []
    if os.path.isdir(SOURCE):
        names = sorted(
            name for name in os.listdir(SOURCE) if os.path.splitext(name)[1].lower() in EXTENSIONS
        )

    lines = [
        "// Generated by scripts/sim_photos.py from sim/photos. Do not edit.",
        "#pragma once",
        "",
        "#include <cstdint>",
        "",
        "struct SimPhoto {",
        "  const char* name;",
        "  const uint8_t* data;",
        "  unsigned length;",
        "  unsigned width;",
        "  unsigned height;",
        "};",
        "",
    ]
    entries = []
    for index, name in enumerate(names):
        target = os.path.join(SHRUNK, os.path.splitext(name)[0] + ".jpg")
        shrink(os.path.join(SOURCE, name), target)
        with open(target, "rb") as handle:
            data = handle.read()
        width, height = jpeg_size(data)
        lines.append(f"static const uint8_t kSimPhotoData{index}[] = {{")
        for start in range(0, len(data), 24):
            lines.append("  " + ",".join(f"0x{b:02x}" for b in data[start : start + 24]) + ",")
        lines.append("};")
        entries.append(
            f"  {{{json.dumps(name)}, kSimPhotoData{index}, {len(data)}, {width}, {height}}},"
        )

    # Drop shrunk copies of photos that were removed from sim/photos.
    kept = {os.path.splitext(name)[0] + ".jpg" for name in names}
    for stale in set(os.listdir(SHRUNK)) - kept:
        os.remove(os.path.join(SHRUNK, stale))

    if entries:
        lines += ["static const SimPhoto kSimPhotos[] = {", *entries, "};"]
    else:
        lines.append('static const SimPhoto kSimPhotos[1] = {{"none", nullptr, 0, 0, 0}};')
    lines += [f"static const unsigned kSimPhotoCount = {len(entries)};", ""]
    text = "\n".join(lines)

    header = os.path.join(GENERATED, "sim_photos.h")
    current = None
    if os.path.exists(header):
        with open(header) as handle:
            current = handle.read()
    if current != text:
        with open(header, "w") as handle:
            handle.write(text)
    print(f"sim_photos: {len(entries)} photo(s) built in from sim/photos")


build()
